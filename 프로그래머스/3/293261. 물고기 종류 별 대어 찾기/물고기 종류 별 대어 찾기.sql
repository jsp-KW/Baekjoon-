# -- 종류별 가장 큰 물고기의 id, 이름, 길이를 출력
-- id에 대해 오름차순으로 정렬











-- 물고기 종류별로 가장 큰 물고기의 정보 출력하기
SELECT F.ID, N.FISH_NAME, F.LENGTH AS 'LENGTH' FROM FISH_INFO F INNER JOIN FISH_NAME_INFO N
ON F.FISH_TYPE = N.FISH_TYPE
WHERE (F.FISH_TYPE, F.LENGTH) IN 
(
    SELECT F.FISH_TYPE, MAX(LENGTH) FROM FISH_INFO F GROUP BY F.FISH_TYPE

)

ORDER BY F.ID ASC;





